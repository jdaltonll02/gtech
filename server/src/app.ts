import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import {corsOrigins} from './config.js';
import {errorHandler} from './core/errors.js';
import {openApi} from './core/openapi.js';
import {accountsRouter} from './modules/accounts/routes.js';
import {opsRouter} from './modules/ops/routes.js';
import {mediaRouter} from './modules/media/routes.js';
import {profilesRouter} from './modules/profiles/routes.js';
import {swipesRouter} from './modules/swipes/routes.js';
import {matchesRouter} from './modules/matches/routes.js';
import {likesRouter} from './modules/likes/routes.js';
import {discoveryRouter} from './modules/discovery/routes.js';
import {chatRouter} from './modules/chat/routes.js';
import {notificationsRouter} from './modules/notifications/routes.js';
import {billingRouter} from './modules/billing/routes.js';
import {safetyRouter} from './modules/safety/routes.js';
import {accountRouter} from './modules/account/routes.js';

export const createApp = () => {
  const app = express();
  app.disable('x-powered-by');
  app.use(helmet());
  app.use(cors({origin: corsOrigins}));
  app.use(express.json({limit: '1mb'}));
  app.use('/api/v1', opsRouter);
  app.use('/api/v1/auth', accountsRouter);
  app.use('/api/v1', profilesRouter);
  app.use('/api/v1', mediaRouter);
  app.use('/api/v1', swipesRouter);
  app.use('/api/v1', matchesRouter);
  app.use('/api/v1', likesRouter);
  app.use('/api/v1', discoveryRouter);
  app.use('/api/v1', chatRouter);
  app.use('/api/v1', notificationsRouter);
  app.use('/api/v1', billingRouter);
  app.use('/api/v1', safetyRouter);
  app.use('/api/v1', accountRouter);
  app.get('/api/v1/schema', (_request, response) => response.json(openApi));
  app.use(errorHandler);
  return app;
};
